package com.rvtec.v2.data

import android.content.Context
import com.google.firebase.FirebaseApp
import com.google.firebase.appcheck.FirebaseAppCheck
import com.google.firebase.appcheck.debug.DebugAppCheckProviderFactory
import com.google.firebase.appcheck.playintegrity.PlayIntegrityAppCheckProviderFactory
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.firestore.SetOptions
import kotlinx.coroutines.tasks.await
import org.json.JSONObject

/**
 * Firebase bootstrap and authenticated cloud snapshot transport.
 * Local SharedPreferences remains the source of truth until a signed-in
 * user explicitly requests synchronization.
 */
class FirebaseServices(context: Context) {
    private val appContext = context.applicationContext

    // Reuse the default app if another startup component initialized it first.
    // Otherwise initialize it from the google-services resources generated by
    // the Google Services Gradle plugin.
    val firebaseApp: FirebaseApp? =
        FirebaseApp.getApps(appContext).firstOrNull { it.name == FirebaseApp.DEFAULT_APP_NAME }
            ?: FirebaseApp.initializeApp(appContext)

    val isConfigured: Boolean
        get() = firebaseApp != null

    fun installAppCheck(): Boolean {
        val configuredApp = firebaseApp ?: return false
        val providerFactory = if (com.rvtec.v2.BuildConfig.DEBUG) {
            DebugAppCheckProviderFactory.getInstance()
        } else {
            PlayIntegrityAppCheckProviderFactory.getInstance()
        }
        FirebaseAppCheck.getInstance(configuredApp).installAppCheckProviderFactory(providerFactory)
        return true
    }

    private fun authenticatedUserId(): String =
        FirebaseAuth.getInstance(requireNotNull(firebaseApp) {
            "Firebase não inicializou. Confira o google-services.json do pacote com.rvtec.manutencao.v2 e a tarefa processDebugGoogleServices."
        }).currentUser?.uid ?: error("Faça login antes de sincronizar os dados.")

    suspend fun uploadSnapshot(snapshot: JSONObject) {
        val configuredApp = requireNotNull(firebaseApp) {
            "Firebase não inicializou. Confira o google-services.json do pacote com.rvtec.manutencao.v2 e a tarefa processDebugGoogleServices."
        }
        val uid = authenticatedUserId()
        FirebaseFirestore.getInstance(configuredApp)
            .collection("users").document(uid)
            .collection("rvtec").document("snapshot")
            .set(mapOf(
                "schemaVersion" to 1,
                "updatedAt" to System.currentTimeMillis(),
                "payload" to snapshot.toString()
            ), SetOptions.merge()).await()
    }

    suspend fun downloadSnapshot(): JSONObject? {
        val configuredApp = requireNotNull(firebaseApp) {
            "Firebase não inicializou. Confira o google-services.json do pacote com.rvtec.manutencao.v2 e a tarefa processDebugGoogleServices."
        }
        val uid = authenticatedUserId()
        val document = FirebaseFirestore.getInstance(configuredApp)
            .collection("users").document(uid)
            .collection("rvtec").document("snapshot").get().await()
        val payload = document.getString("payload") ?: return null
        return JSONObject(payload)
    }
}
